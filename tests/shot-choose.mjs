import { chromium } from 'playwright';
import path from 'path';
const [out, w, step] = [process.argv[2], +process.argv[3], process.argv[4]];
const b = await chromium.launch(); const pg = await b.newPage({ viewport: { width: w, height: 800 }, deviceScaleFactor: 2 });
await pg.route(/gstatic|googleapis|firebase/, r => r.abort());
await pg.goto('file://' + path.resolve('../index.html'), { waitUntil: 'domcontentloaded' });
await pg.waitForTimeout(800);
await pg.evaluate((step) => { document.querySelectorAll('body > *').forEach(e => { if (e.id !== 'loginScreen') e.style.display = 'none'; });
  const l = document.getElementById('loginScreen'); l.hidden = false; l.style.display = 'grid'; loginStep(step); }, step);
await pg.waitForTimeout(600);
await pg.screenshot({ path: out });
await b.close();
